const BY = new Map(GLYPHS.map((x) => [x.char, x]));

/** The glyph of a character (throws for one we have not drawn). */
export function glyphOf(char: string): Glyph {
  const x = BY.get(char === "-" ? "−" : char);
  if (!x) throw new Error(`Sin glifo para «${char}»`);
  return x;
}
export const hasGlyph = (char: string): boolean => BY.has(char === "-" ? "−" : char);
